#!/bin/sh
# Build the Flutter release bundle and package it as a Flatpak.
#
# Environment:
#   REPO_DIR         export repository (default: build/flatpak-repo)
#   BUILDER          flatpak-builder command (default: flatpak run org.flatpak.Builder)
#   FLATPAK_GPG_KEY  key ID/fingerprint used to sign commits and summaries
#   FLATPAK_GPG_HOME GNUPGHOME containing that key
set -eu

# shellcheck disable=SC1007
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$ROOT"

REPO_DIR=${REPO_DIR:-$ROOT/build/flatpak-repo}
BUILDER=${BUILDER:-"flatpak run org.flatpak.Builder"}
BUILD_DIR=$ROOT/build/flatpak-build

flutter build linux --release

rm -rf "$ROOT/flatpak/bundle" "$ROOT/flatpak/sidecar" "$ROOT/flatpak/data"
cp -a "$ROOT/build/linux/x64/release/bundle" "$ROOT/flatpak/bundle"
cp -a "$ROOT/sidecar" "$ROOT/flatpak/sidecar"
cp -a "$ROOT/data" "$ROOT/flatpak/data"
find "$ROOT/flatpak/sidecar" -type d \( -name __pycache__ -o -name .pytest_cache \) -prune -exec rm -rf {} +

mkdir -p "$REPO_DIR" "$BUILD_DIR"
$BUILDER --force-clean --repo="$REPO_DIR" --arch=x86_64 "$BUILD_DIR" "$ROOT/flatpak/io.github.vellum.Vellum.yml"

if [ -n "${FLATPAK_GPG_KEY:-}" ]; then
  GPG_ARGS="--gpg-sign=$FLATPAK_GPG_KEY"
  if [ -n "${FLATPAK_GPG_HOME:-}" ]; then
    GPG_ARGS="$GPG_ARGS --gpg-homedir=$FLATPAK_GPG_HOME"
  fi
  mkdir -p "$REPO_DIR/refs/remotes"

  # The builder exports unsigned commits; re-export the app commit signed and
  # refresh appstream before signing its commits.
  # shellcheck disable=SC2086
  flatpak build-export $GPG_ARGS --update-appstream --arch=x86_64 \
    "$REPO_DIR" "$BUILD_DIR" master

  # Appstream commits are generated by build-update-repo, which only signs the
  # summary. Sign each appstream commit through a temporary app ref.
  # shellcheck disable=SC2086
  flatpak build-update-repo $GPG_ARGS --generate-static-deltas "$REPO_DIR"
  for ref in appstream/x86_64 appstream2/x86_64; do
    [ -f "$REPO_DIR/refs/heads/$ref" ] || continue
    commit=$(cat "$REPO_DIR/refs/heads/$ref")
    ostree --repo="$REPO_DIR" refs \
      --create=app/io.github.vellum.Temp/x86_64/master --force "$commit"
    # shellcheck disable=SC2086
    flatpak build-sign $GPG_ARGS --arch=x86_64 \
      "$REPO_DIR" io.github.vellum.Temp master
    ostree --repo="$REPO_DIR" refs \
      --delete app/io.github.vellum.Temp/x86_64/master
  done

  # Re-sign the summary without regenerating the now-signed appstream branch.
  # shellcheck disable=SC2086
  flatpak build-update-repo $GPG_ARGS --no-update-appstream \
    --generate-static-deltas "$REPO_DIR"
fi
